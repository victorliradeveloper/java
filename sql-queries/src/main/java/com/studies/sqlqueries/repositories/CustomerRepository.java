package com.studies.sqlqueries.repositories;

import com.studies.sqlqueries.entities.Customer;
import com.studies.sqlqueries.enums.CustomerStatus;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.Modifying;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.query.Param;

import java.util.List;
import java.util.Optional;

public interface CustomerRepository extends JpaRepository<Customer, Long> {

    // ==================== SIMPLE ====================
    // Spring Data derives SQL from the method name automatically.

    // SQL: SELECT * FROM customers WHERE email = ?
    Optional<Customer> findByEmail(String email);

    // SQL: SELECT * FROM customers WHERE status = ?
    List<Customer> findByStatus(CustomerStatus status);

    // SQL: SELECT * FROM customers WHERE loyalty_points > ?
    List<Customer> findByLoyaltyPointsGreaterThan(int points);

    // ==================== MEDIUM ====================

    // SQL: SELECT * FROM customers WHERE status = ? AND loyalty_points >= ?
    List<Customer> findByStatusAndLoyaltyPointsGreaterThanEqual(CustomerStatus status, int points);

    // JOIN to customer_addresses — equivalent to MongoDB dot-notation on an array field.
    // MongoDB: { 'addresses.city': ?0 }
    //   → checks every element of the array
    // SQL: the JOIN naturally iterates every row in customer_addresses for that customer.
    // DISTINCT avoids returning the same customer multiple times when they have several addresses.
    @Query("SELECT DISTINCT c FROM Customer c JOIN c.addresses a WHERE a.city = :city")
    List<Customer> findByCity(@Param("city") String city);

    // JOIN with two conditions on the SAME address row.
    // MongoDB: { 'addresses': { $elemMatch: { 'city': ?0, 'state': ?1 } } }
    //   → $elemMatch ensures city AND state must come from the same array element.
    // SQL: because both conditions are on alias 'a' (a single customer_addresses row),
    //   the JOIN automatically guarantees that city AND state are in the same row.
    @Query("SELECT DISTINCT c FROM Customer c JOIN c.addresses a WHERE a.city = :city AND a.state = :state")
    List<Customer> findByCityAndState(@Param("city") String city, @Param("state") String state);

    // ILIKE = case-insensitive LIKE in PostgreSQL.
    // MongoDB: { 'name': { $regex: ?0, $options: 'i' }, 'status': ?1 }
    // SQL: WHERE name ILIKE '%pattern%' AND status = 'VALUE'
    @Query(nativeQuery = true,
           value = "SELECT * FROM customers WHERE name ILIKE CONCAT('%', :name, '%') AND status = :status")
    List<Customer> findByNameContainingAndStatus(@Param("name") String name, @Param("status") String status);

    // ==================== COMPLEX ====================

    // OR combining two independent condition groups.
    // MongoDB: { $or: [ { status:'ACTIVE', loyaltyPoints:{$gte:?0} }, { status:'INACTIVE', loyaltyPoints:{$gte:?1} } ] }
    // SQL: (status = 'ACTIVE' AND ...) OR (status = 'INACTIVE' AND ...)
    @Query(nativeQuery = true, value = """
            SELECT * FROM customers
            WHERE (status = 'ACTIVE'   AND loyalty_points >= :activeThreshold)
               OR (status = 'INACTIVE' AND loyalty_points >= :inactiveThreshold)
            """)
    List<Customer> findVipCustomers(@Param("activeThreshold") int activeThreshold,
                                    @Param("inactiveThreshold") int inactiveThreshold);

    // JOIN + NOT IN / <> filter.
    // MongoDB: { 'addresses': { $elemMatch: { 'country': ?0 } }, 'status': { $ne: 'SUSPENDED' } }
    // SQL: JOIN on customer_addresses + WHERE status <> 'SUSPENDED'
    @Query(nativeQuery = true, value = """
            SELECT DISTINCT c.* FROM customers c
            JOIN customer_addresses ca ON ca.customer_id = c.id
            WHERE ca.country = :country AND c.status <> 'SUSPENDED'
            """)
    List<Customer> findActiveCustomersByCountry(@Param("country") String country);

    // SIZE() generates a correlated subquery COUNT.
    // MongoDB: { $expr: { $gt: [ { $size: '$addresses' }, 1 ] } }
    // SQL (generated by Hibernate):
    //   WHERE (SELECT COUNT(*) FROM customer_addresses WHERE customer_id = c.id) > 1
    @Query("SELECT c FROM Customer c WHERE SIZE(c.addresses) > 1")
    List<Customer> findCustomersWithMultipleAddresses();

    // $and with three conditions: status exclusion + minimum points + country filter via JOIN.
    // MongoDB: { $and: [ { status:{$ne:'SUSPENDED'} }, { loyaltyPoints:{$gte:?0} }, { addresses:{$elemMatch:{country:'Brazil'}} } ] }
    // SQL: standard WHERE with AND + JOIN to filter by address country
    @Query(nativeQuery = true, value = """
            SELECT DISTINCT c.* FROM customers c
            JOIN customer_addresses ca ON ca.customer_id = c.id
            WHERE c.status <> 'SUSPENDED'
              AND c.loyalty_points >= :minPoints
              AND ca.country = 'Brazil'
            """)
    List<Customer> findHighValueBrazilianCustomers(@Param("minPoints") int minPoints);

    // ==================== BASIC UPDATE ====================

    // MongoDB: $set → SQL: UPDATE ... SET field = value WHERE id = ?
    // @Modifying marca que esta query modifica dados (UPDATE/DELETE), não apenas lê.
    // Sem ele, o Spring Data lançaria uma exceção ao executar.
    @Modifying
    @Query("UPDATE Customer c SET c.phone = :phone WHERE c.id = :id")
    int updatePhone(@Param("id") Long id, @Param("phone") String phone);

    // MongoDB: $set → SQL: UPDATE ... SET status = ? WHERE id = ?
    @Modifying
    @Query("UPDATE Customer c SET c.status = :status WHERE c.id = :id")
    int updateStatus(@Param("id") Long id, @Param("status") CustomerStatus status);

    // ==================== MEDIUM UPDATE ====================

    // MongoDB: $inc → SQL: SET field = field + delta
    // A expressão "c.loyaltyPoints + :delta" é avaliada pelo banco — operação atômica.
    @Modifying
    @Query("UPDATE Customer c SET c.loyaltyPoints = c.loyaltyPoints + :delta WHERE c.id = :id")
    int addLoyaltyPoints(@Param("id") Long id, @Param("delta") int delta);

    // ==================== ADVANCED UPDATE ====================

    // MongoDB: updateMulti → SQL: UPDATE sem WHERE por id — afeta N linhas.
    // Retorna o número de linhas afetadas.
    @Modifying
    @Query("UPDATE Customer c SET c.status = :newStatus WHERE c.status = :currentStatus AND c.loyaltyPoints < :maxPoints")
    int bulkUpdateStatus(@Param("currentStatus") CustomerStatus currentStatus,
                         @Param("newStatus") CustomerStatus newStatus,
                         @Param("maxPoints") int maxPoints);
}
